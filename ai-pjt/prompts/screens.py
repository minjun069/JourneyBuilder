def screen_context(step_id: str) -> dict[str, str]:
    """Resolve only the current trusted screen; never send the whole catalog."""
    try:
        title, description = SCREEN_DESCRIPTIONS[step_id]
    except (KeyError, TypeError) as error:
        raise ValueError(f"unknown service screen: {step_id}") from error
    return {"화면": title, "목적과 안내 범위": description}
