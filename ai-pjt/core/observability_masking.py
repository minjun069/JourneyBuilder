"""Masking-safe log and trace serialization for typed instrumentation events."""

from __future__ import annotations

from collections.abc import Mapping
from hashlib import sha256
import logging
import re
from typing import Any, Protocol

from core.masking import MaskingPolicy, MaskingSink, mask_payload
from core.runtime_instrumentation import (
    InstrumentationEvent,
    InstrumentationPort,
)
from core.runtime_instrumentation_adapter import RuntimeInstrumentationAdapter


class SerializedInstrumentationSink(Protocol):
    def emit(self, payload: Mapping[str, Any]) -> None: ...


def mask_application_log_payload(
    payload: Any,
    *,
    policy: MaskingPolicy,
) -> Any:
    return mask_payload(
        payload,
        sink=MaskingSink.APPLICATION_LOG,
        policy=policy,
    )


def exception_identity_fields(error: BaseException) -> dict[str, str]:
    """Return non-content diagnostics suitable for trace metadata.

    Provider and parsing exceptions can contain the full model request in
    their message. Observability therefore retains only the deepest exception
    type and a stable one-way fingerprint; raw exception text is discarded.
    """

    root = error
    visited: set[int] = set()
    while root.__cause__ is not None and id(root) not in visited:
        visited.add(id(root))
        root = root.__cause__
    error_type = type(root).__name__
    error_module = type(root).__module__
    try:
        message = str(root)
    except Exception:  # noqa: BLE001 - exception rendering may itself fail
        message = "<exception text unavailable>"
    material = f"{error_module}:{error_type}:{message}".encode(
        "utf-8",
        errors="replace",
    )
    return {
        "error_type": error_type,
        "error_fingerprint": sha256(material).hexdigest()[:24],
    }


def masked_exception_fields(
    error: BaseException,
    *,
    pseudonym_key: bytes | None = None,
    **context: Any,
) -> dict[str, Any]:
    """Serialize one caught exception without copying unstructured raw text.

    Provider and validation exceptions can quote arbitrary model input. Because
    a free-form exception string cannot be classified completely, logs retain
    only its type, module, stable fingerprint, and separately typed context.
    """

    fields: dict[str, Any] = {
        **context,
        "error_type": type(error).__name__,
        "error_module": type(error).__module__,
        **exception_identity_fields(error),
    }

    try:
        key = (
            pseudonym_key
            if pseudonym_key is not None
            else _runtime_pseudonym_key()
        )
        masked = mask_application_log_payload(
            fields,
            policy=MaskingPolicy(pseudonym_key=key),
        )
    except Exception:  # noqa: BLE001 - never fall back to unmasked text
        return {
            "error_type": type(error).__name__,
            "error_module": type(error).__module__,
            "masking_status": "failed_closed",
        }
    if not isinstance(masked, Mapping):
        return {"masking_status": "failed_closed"}
    return dict(masked)


def _runtime_pseudonym_key() -> bytes:
    from core.config import settings

    return settings.masking_pseudonym_key_bytes


def mask_trace_payload(
    payload: Any,
    *,
    policy: MaskingPolicy,
) -> Any:
    return mask_payload(
        payload,
        sink=MaskingSink.TRACE_EXPORT,
        policy=policy,
    )


class MaskedInstrumentationSink:
    """Serialize typed events, mask them, and isolate exporter failures.

    The downstream receives only the masked mapping. A masking or exporter
    failure drops that one export and never retries with the raw event.
    """

    __slots__ = ("_downstream", "_policy", "_sink", "_dropped_exports")

    def __init__(
        self,
        *,
        policy: MaskingPolicy,
        sink: MaskingSink,
        downstream: SerializedInstrumentationSink,
    ) -> None:
        if not isinstance(policy, MaskingPolicy):
            raise TypeError("MaskedInstrumentationSink requires a MaskingPolicy")
        if sink not in {MaskingSink.APPLICATION_LOG, MaskingSink.TRACE_EXPORT}:
            raise ValueError(
                "instrumentation sink must be application_log or trace_export"
            )
        if not callable(getattr(downstream, "emit", None)):
            raise TypeError("serialized instrumentation downstream is required")
        self._policy = policy
        self._sink = sink
        self._downstream = downstream
        self._dropped_exports = 0

    def emit(self, event: InstrumentationEvent) -> None:
        try:
            raw = event.to_dict()
            masked = mask_payload(raw, sink=self._sink, policy=self._policy)
            if not isinstance(masked, Mapping):
                raise TypeError("masked instrumentation event must be a mapping")
            # A SHA-256 prompt hash is generated by the registered prompt, not
            # customer content. A phone-shaped substring inside it must not
            # corrupt the machine token and drop the entire MODEL observation.
            prompt_hash = raw.get("prompt_hash")
            if (
                raw.get("event_family") == "operation"
                and raw.get("stage") == "model"
                and isinstance(prompt_hash, str)
                and re.fullmatch(r"[0-9a-f]{64}", prompt_hash)
            ):
                masked = {**masked, "prompt_hash": prompt_hash}
            self._downstream.emit({**masked, "masking_status": "applied"})
        except Exception:
            self._dropped_exports += 1

    @property
    def dropped_exports(self) -> int:
        return self._dropped_exports


class StructuredLogInstrumentationExporter:
    """Write an already-masked event to the application logging backend."""

    __slots__ = ("_logger",)

    def __init__(self, logger: logging.Logger) -> None:
        if not isinstance(logger, logging.Logger):
            raise TypeError("a logging.Logger is required")
        self._logger = logger

    def emit(self, payload: Mapping[str, Any]) -> None:
        self._logger.info(
            "ai_instrumentation_event",
            extra={"instrumentation_event": dict(payload)},
        )


class FakeSerializedInstrumentationSink:
    """In-memory sink that can also simulate an unavailable trace store."""

    def __init__(self, *, fail: bool = False) -> None:
        self._fail = fail
        self._payloads: list[dict[str, Any]] = []

    def emit(self, payload: Mapping[str, Any]) -> None:
        self._payloads.append(dict(payload))
        if self._fail:
            raise RuntimeError("simulated instrumentation store outage")

    @property
    def payloads(self) -> tuple[dict[str, Any], ...]:
        return tuple(self._payloads)


def build_masked_runtime_instrumentation(
    *,
    pseudonym_key: bytes,
    downstream: SerializedInstrumentationSink,
    sink: MaskingSink,
) -> tuple[RuntimeInstrumentationAdapter, MaskedInstrumentationSink]:
    policy = MaskingPolicy(pseudonym_key=pseudonym_key)
    masked_sink = MaskedInstrumentationSink(
        policy=policy,
        sink=sink,
        downstream=downstream,
    )
    return (
        RuntimeInstrumentationAdapter(InstrumentationPort(masked_sink)),
        masked_sink,
    )
