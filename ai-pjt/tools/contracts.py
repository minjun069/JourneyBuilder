from __future__ import annotations

from collections.abc import Awaitable, Callable, Mapping
from dataclasses import dataclass
from enum import Enum
from time import monotonic
from typing import Any


TOOL_CONTRACT_VERSION = "1.0"


class ToolErrorCode(str, Enum):
    UNKNOWN_TOOL = "UNKNOWN_TOOL"
    FORBIDDEN = "TOOL_FORBIDDEN"
    CONTEXT_MISMATCH = "TOOL_CONTEXT_MISMATCH"
    INVALID_ARGUMENTS = "INVALID_TOOL_ARGUMENTS"
    DEADLINE_EXCEEDED = "TOOL_TIMEOUT"
    BUDGET_EXCEEDED = "TOOL_BUDGET_EXCEEDED"
    NOT_FOUND = "TOOL_RESOURCE_NOT_FOUND"
    DEPENDENCY_UNAVAILABLE = "TOOL_DEPENDENCY_UNAVAILABLE"
    INVALID_RESULT = "INVALID_TOOL_RESULT"
    INTERNAL_ERROR = "TOOL_INTERNAL_ERROR"


@dataclass(frozen=True)
class ToolError:
    code: ToolErrorCode
    message: str
    retryable: bool = False
    details: tuple[dict[str, Any], ...] = ()

    def to_dict(self) -> dict[str, Any]:
        return {
            "code": self.code.value,
            "message": self.message,
            "retryable": self.retryable,
            "details": list(self.details),
        }


@dataclass(frozen=True)
class ToolCallResult:
    tool_name: str
    tool_version: str
    ok: bool
    data: dict[str, Any] | None = None
    error: ToolError | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "contract_version": TOOL_CONTRACT_VERSION,
            "tool_name": self.tool_name,
            "tool_version": self.tool_version,
            "ok": self.ok,
            "data": self.data,
            "error": self.error.to_dict() if self.error else None,
        }


@dataclass(frozen=True)
class ToolAuditEvent:
    request_id: str
    task_id: str
    step_id: str
    task_type: str
    tool_name: str
    tool_version: str
    agent: str
    decision: str
    status: str
    duration_ms: int
    argument_classes: tuple[str, ...]
    call_source: str
    error_code: str | None = None

    def to_dict(self) -> dict[str, Any]:
        # Deliberately excludes raw arguments and tool result values.
        return {
            "request_id": self.request_id,
            "task_id": self.task_id,
            "step_id": self.step_id,
            "task_type": self.task_type,
            "tool_name": self.tool_name,
            "tool_version": self.tool_version,
            "agent": self.agent,
            "decision": self.decision,
            "status": self.status,
            "duration_ms": self.duration_ms,
            "argument_classes": list(self.argument_classes),
            "call_source": self.call_source,
            "error_code": self.error_code,
        }


KnowledgeSearch = Callable[
    [str, int],
    Awaitable[list[dict[str, Any]]],
]
AuditSink = Callable[[ToolAuditEvent], None]


@dataclass(frozen=True)
class ToolExecutionContext:
    """Trusted values injected by the AI runtime, never generated by the model."""

    request_id: str
    step_id: str
    agent: str
    task_type: str = "answer_question"
    task_id: str = "task-unknown"
    call_source: str = "graph_task"
    field_registry: tuple[dict[str, Any], ...] = ()
    knowledge_search: KnowledgeSearch | None = None
    deadline_at_monotonic: float | None = None
    audit_sink: AuditSink | None = None

    def remaining_seconds(self) -> float | None:
        if self.deadline_at_monotonic is None:
            return None
        return max(0.0, self.deadline_at_monotonic - monotonic())


class ToolInvocationError(Exception):
    def __init__(
        self,
        code: ToolErrorCode,
        message: str,
        *,
        retryable: bool = False,
        details: tuple[dict[str, Any], ...] = (),
    ) -> None:
        super().__init__(message)
        self.error = ToolError(
            code=code,
            message=message,
            retryable=retryable,
            details=details,
        )


ToolHandler = Callable[
    [ToolExecutionContext, dict[str, Any]],
    Awaitable[dict[str, Any]],
]


@dataclass(frozen=True)
class FunctionToolDefinition:
    name: str
    description: str
    input_schema: dict[str, Any]
    output_schema: dict[str, Any]
    allowed_agents: frozenset[str]
    allowed_task_types: frozenset[str]
    handler: ToolHandler
    version: str = "1.0"
    timeout_seconds: float = 3.0
    argument_classes: tuple[str, ...] = ()
